      fire: { lv: 'p', exp: (a, b) => `${a.l} ו${b.l} שניהם קשורים לאש — אנרגיה שמשנה את מה שנוגעת בו.` },
      earth: { lv: 'p', exp: (a, b) => `${a.l} ו${b.l} שניהם בני האדמה — יציבים, עתיקים, אדישים לזמן.` },
      gem: { lv: 'r', exp: (a, b) => `${a.l} ו${b.l} שניהם אבנים יקרות — שניהם נוצרו בתנאים קיצוניים ושניהם מגלמים יופי נצחי.` },
      science: { lv: 'r', exp: (a, b) => `${a.l} ו${b.l} שניהם כלי מדע — שניהם פותחים צוהר לעולם שלא נראה בעין.` },
